import 'package:flutter/foundation.dart';

/// Current language: 'ar' (default) or 'en'.
final ValueNotifier<String> langNotifier = ValueNotifier<String>('ar');

bool get isAr => langNotifier.value == 'ar';

String tr(String key) {
  final lang = _strings[langNotifier.value];
  return lang?[key] ?? _strings['en']![key] ?? key;
}

/// Picks the Arabic version of a field (name_ar) when the app is in Arabic.
String loc(Map<String, dynamic> m, String key) {
  if (isAr) {
    final ar = m['${key}_ar'];
    if (ar is String && ar.isNotEmpty) return ar;
  }
  final v = m[key];
  return v is String ? v : '';
}

String money(num v) {
  final s = v == v.roundToDouble() ? v.toStringAsFixed(0) : v.toStringAsFixed(3);
  return isAr ? '$s د.ب' : 'BD $s';
}

String monthLabel(DateTime d) => '${tr('mo${d.month}')} ${d.year}';

/// '06:00' -> '6:00 AM' (or ص / م in Arabic)
String fmtTime(String hhmm) {
  final parts = hhmm.split(':');
  final h = int.parse(parts[0]);
  final suffix = h >= 12 ? (isAr ? 'م' : 'PM') : (isAr ? 'ص' : 'AM');
  final h12 = h % 12 == 0 ? 12 : h % 12;
  return '$h12:${parts[1]} $suffix';
}

